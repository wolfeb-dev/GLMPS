// apps/shell/src/lib/launch-auth.js
// A copy of the kernel's challenge-response primitives (parity-tested,
// apps/shell/test/launch-auth-parity.test.js, which also compares the two
// files' code with comments stripped): the shell package must not import
// server code at runtime, so this is the same code as
// server/lib/governance/launch-auth.js. nonceTime is used only by the
// kernel's nonce guard; it is kept here so the copies stay identical.
//
// the
// shell used to send the raw launch token to whoever answered on the
// loopback kernel URL - an impostor on that port (the real service down,
// another local account) could ignore the token entirely, serve forged
// records and a forged terminal allowlist, 200 the claim, and harvest the
// token outright. The token now NEVER leaves either process; each side
// proves KNOWLEDGE of it via HMAC-SHA256 instead.
//
// Protocol (fix round 4, F2: one nonce per request, generated by the shell):
//   message(direction) = `${direction}\n${METHOD}\n${pathAndQuery}\n${nonce}\n${bodyHash}`
//     direction    'req' (shell -> kernel) or 'res' (kernel -> shell)
//     METHOD       the request's HTTP method, upper-cased
//     pathAndQuery the request target exactly as the kernel receives it
//                  (req.url; the shell signs new URL(...).pathname + search)
//     nonce        randomNonce(): 12 hex digits of mint time (ms) followed
//                  by 32 hex digits from the OS RNG
//     bodyHash     sha256Hex of the body bytes ('' for none)
//   inbound proof  (headers X-Launch-Nonce / X-Launch-Proof):
//     HMAC-SHA256(token, message('req') over the request body). The kernel
//     recomputes it from the method, target and body it ACTUALLY received
//     and refuses (401) on any mismatch, before ever touching the broker.
//     Only after the proof verifies, the kernel's nonce guard
//     (launch-nonces.js) refuses a nonce minted outside its freshness
//     window or one it has already accepted.
//   outbound proof (header X-Launch-Response-Proof):
//     HMAC-SHA256(token, message('res') over the response body), reusing
//     the request's own nonce, method and target. The shell recomputes it
//     from the response it actually received and refuses to trust ANY of
//     that response's content - the record, the cwd, the terminal
//     allowlist - on a mismatch.
// What this does and does not stop: a proof captured by an impostor fits
// exactly one direction, one method, one target (so one launch id) and one
// body, and the real kernel accepts its nonce at most once and only inside
// the freshness window. Round 3's claim that replaying the identical
// request was "harmless by idempotency" was wrong: a proof over '' from a
// GET poll verified on claim and result too, and a response proof verified
// as a request proof. The residual is a captured-but-never-delivered
// request (the impostor swallowed it) replayed to the real kernel inside
// the window: it can only repeat that one request, on that one target.
import crypto from 'node:crypto';

const DIRECTIONS = new Set(['req', 'res']);
const TIME_HEX = 12;
const RANDOM_HEX = 32;

export function sha256Hex(s) { return crypto.createHash('sha256').update(String(s ?? '')).digest('hex'); }

export function computeProof(token, { direction, method, path, nonce, bodyHash }) {
  if (!DIRECTIONS.has(direction)) throw new Error(`launch-auth: unknown proof direction ${direction}`);
  const message = `${direction}\n${String(method).toUpperCase()}\n${path}\n${nonce}\n${bodyHash}`;
  return crypto.createHmac('sha256', token).update(message).digest('hex');
}

// Constant-time by length-then-timingSafeEqual; an empty/missing proof on
// either side never "matches" even against itself (so a caller that
// forgets to check for presence first cannot be tricked by two absent
// values comparing equal).
export function proofsMatch(a, b) {
  if (!a || !b) return false;
  const bufA = Buffer.from(String(a), 'utf8');
  const bufB = Buffer.from(String(b), 'utf8');
  if (bufA.length !== bufB.length) return false;
  return crypto.timingSafeEqual(bufA, bufB);
}

export function randomNonce(now = Date.now()) {
  return Math.trunc(now).toString(16).padStart(TIME_HEX, '0').slice(-TIME_HEX) + crypto.randomBytes(RANDOM_HEX / 2).toString('hex');
}

// The mint time randomNonce embedded, or null for anything not shaped
// like one of its nonces.
export function nonceTime(nonce) {
  if (typeof nonce !== 'string' || !new RegExp(`^[0-9a-f]{${TIME_HEX + RANDOM_HEX}}$`).test(nonce)) return null;
  return parseInt(nonce.slice(0, TIME_HEX), 16);
}
