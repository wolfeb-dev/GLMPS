// server/lib/orchestration/worktree-sweeper.js
// Lifecycle for session worktrees (glmps-71 A4): a session/<project>/<shortid>
// worktree whose session has ended AND whose branch carries zero unmerged
// commits is safe to sweep (worktree remove + branch delete). One still
// carrying unmerged commits is exactly the finished-but-unmerged miss
// (server/lib/observability/unmerged-branches.js) and must survive - it is
// surfaced there instead, with a link back to the session.
//
// House split: pure recipes + pure decision core (`planSweep`) here; the
// impure edge (`sweepSessionWorktrees`) takes an injected `exec(file, args) ->
// stdout` (server passes an execFileSync wrapper; tests pass a fake - never
// real git in tests). Every git failure is per-item fail-open: skip that item
// rather than throw, so a flaky repo can never break the sweep of everything
// else, and a dirty tree (which `git worktree remove` without --force refuses
// to touch) simply survives as "kept".
import {
  listWorktreesRecipe, parseWorktreeList, worktreePruneRecipe,
  isUnderDir as underDir,
} from './worktrees.js';
import {
  forEachRefRecipe, parseRefList, cherryFor, resolveDefaultBase,
} from '../observability/unmerged-branches.js';

const SESSION_BRANCH_RE = /^session\//;
// Queue-runner job worktrees: `glmps-runner/<project>/<jobId>` (worktrees.js
// worktreePlan). The tail after the project segment is the backlog card id,
// which is the identity the runner ledger is keyed by - see `liveJobIds`.
const RUNNER_BRANCH_RE = /^glmps-runner\//;
// Branch names the worktree tooling generates for itself. These are never
// hand-created, so a merged one with no worktree left is pure debris (glmps-117:
// 7 of them were deleted by hand on 2026-07-22). `-d` still refuses anything
// unmerged, so widening the orphan pass to these cannot destroy work.
// glmps-runner/* joined this list in glmps-162: when `worktree remove` fails
// (it did, on Windows, on 2026-07-29) the follow-up `branch -d` never runs and
// the branch outlives its worktree forever because nothing ever retried it.
const TOOLING_BRANCH_RE = /^(?:worktree-agent-|lane-)/;
// card/<id> is the hand-named branch a self-worked card uses (not generated by
// the worktree tooling, so it needed adding here). Still merged-only via `-d`.
const CARD_BRANCH_RE = /^card\//;
const sweepableOrphanBranch = (name) =>
  SESSION_BRANCH_RE.test(name) || TOOLING_BRANCH_RE.test(name) || RUNNER_BRANCH_RE.test(name) || CARD_BRANCH_RE.test(name);

/**
 * The runner job id a branch belongs to, or null if it is not a runner branch.
 * `glmps-runner/<project>/<jobId>`: everything after the project segment, so a
 * job id containing a slash still round-trips. Callers match it EXACTLY against
 * the ledger, because job `mc-3` must never be read as protecting `mc-33`.
 */
export function jobIdFromRunnerBranch(branch) {
  const name = String(branch ?? '');
  if (!RUNNER_BRANCH_RE.test(name)) return null;
  return name.split('/').slice(2).join('/') || null;
}

/** Is this branch's runner job still in the ledger, i.e. still in flight? */
function heldByLiveJob(branch, liveJobs) {
  const jobId = jobIdFromRunnerBranch(branch);
  return !!jobId && liveJobs.has(jobId);
}

// Deliberately NOT worktrees.js's worktreeRemoveRecipe (`--force`): a dirty
// session worktree must survive the sweep, not be blown away, so we omit
// --force here and let a non-clean tree fail the exec and fall through to
// "kept".
export function worktreeRemoveSafeRecipe({ repo, dir }) {
  return { file: 'git', args: ['-C', repo, 'worktree', 'remove', dir] };
}
// `-d` (not `-D`): refuses to delete a branch with unmerged commits, so even
// if a commit raced in between the cherry-check and this delete, the branch
// survives instead of being force-deleted out from under someone.
export function deleteBranchRecipe({ repo, branch }) {
  return { file: 'git', args: ['-C', repo, 'branch', '-d', branch] };
}

function toPair(recipe) { return [recipe.file, recipe.args]; }


/**
 * Decide which orchestrator-owned worktrees are safe to remove.
 *
 * CONTRACT (rewritten in glmps-162; the previous version of this comment said
 * "glmps-runner/* job worktrees are always kept untouched", which glmps-117 had
 * already made false and which is precisely the safety property that then
 * failed in production on 2026-07-29). Candidacy is CONTAINMENT in `managedDir`
 * plus `session/*` anywhere. A runner job worktree lives under `managedDir`, so
 * it IS a candidate and is protected by identity, not by exemption:
 *   - `session/*`         -> protected while its session id is in liveSessionIds
 *   - `glmps-runner/*`    -> protected while its job id is in liveJobIds
 *   - anything else       -> protected only by occupancy (liveDirs) + unmerged
 * Unmerged commits keep ANY worktree, regardless of the above.
 *
 * @param worktrees      parsed `git worktree list` entries [{ dir, branch, head }]
 * @param liveSessionIds session ids that are still running, never sweep these
 * @param liveDirs       cwds of non-ended sessions: a worktree that IS (or
 *                       contains) a live session's cwd is never swept. This is
 *                       the protection that actually covers terminal launches,
 *                       whose worktree shortid is a random launch-time id the
 *                       eventual session id never matches.
 * @param liveJobIds     runner ledger keys (backlog card ids) with a job in
 *                       flight. Needed because a runner branch encodes no
 *                       session id, so liveSessionIds cannot reach it, and
 *                       occupancy alone is RACY: between `git worktree add` and
 *                       the launched agent appearing in sessionSummaries() with
 *                       a cwd, a fresh job worktree is unoccupied, merged and
 *                       therefore removable. That window is what destroyed
 *                       glmps-33's checkout while its agent was live.
 * @param cherryByBranch { [branch]: { unmerged, equivalent } } patch-equivalence vs. the default branch
 * @param managedDir     the worktrees dir this orchestrator owns. Anything under
 *                       it is a sweep candidate regardless of branch name
 *                       (glmps-117). Omit to keep the old session/*-only rule.
 * @returns { remove: [{ dir, branch }], keep: [entry, ...] }
 */
export function planSweep({ worktrees = [], liveSessionIds = [], liveDirs = [], liveJobIds = [], cherryByBranch = {}, managedDir = null } = {}) {
  const live = new Set(liveSessionIds);
  const liveJobs = new Set(liveJobIds);
  const remove = [];
  const keep = [];
  for (const w of worktrees) {
    const branch = w?.branch ?? '';
    // glmps-117: candidacy is "we created it", which is containment in the
    // managed dir, NOT the branch name. The old session/* rule missed every
    // worktree made by the harness's Agent(isolation:'worktree') tool and by the
    // orchestrator's own lane-*/agent-* dirs, so they accumulated forever (17
    // reaped by hand on 2026-07-22). session/* still qualifies wherever it lives,
    // so nothing that used to be swept stops being swept.
    const isSession = SESSION_BRANCH_RE.test(branch);
    const isManaged = !!managedDir && underDir(w.dir, managedDir);
    if (!isSession && !isManaged) { keep.push(w); continue; }
    // A detached worktree has no branch to cherry against, so its merge status
    // used to default to "fully merged" and it was swept mid-use: the merge
    // queue's test and review checkouts are detached and remove themselves.
    if (!w?.branch) { keep.push(w); continue; }
    // Only a session/* branch encodes its session id; a managed worktree on an
    // ordinary feature branch is protected by the liveDirs occupancy check below.
    const sid = isSession ? branch.split('/').pop() : null;
    const unmerged = cherryByBranch[branch]?.unmerged ?? 0;
    const occupied = liveDirs.some(d => underDir(d, w.dir));
    // glmps-162: the runner's ledger is this worktree's lease. Checked BEFORE
    // occupancy on purpose, because the whole point is that occupancy is not yet
    // observable when the job is youngest and the damage is worst. It is a lease
    // and not an exemption: once the job leaves the ledger the worktree becomes
    // reclaimable again like any other, so these cannot accumulate.
    const leased = heldByLiveJob(branch, liveJobs);
    if (!leased && !occupied && !(sid && live.has(sid)) && unmerged === 0) remove.push({ dir: w.dir, branch });
    else keep.push(w);
  }
  return { remove, keep };
}

//
// `exec(file, args) -> stdout | Promise<stdout>` is async so a repo's git
// calls never block the Node event loop (server injects an async execFile
// wrapper; tests pass a plain synchronous fake - `await`ing a non-Promise
// resolves immediately, so both work unchanged). Independent, read-only git
// calls (the per-branch cherry-checks below) run concurrently via
// Promise.all - this was the O(branches) hot spot: this sweep previously ran
// execFileSync per branch per repo on every inventory-scan tick (default
// every 60s) AND once synchronously at server boot, which is what turned a
// junk-inflated root list (see the isProjectRootCandidate filter added to the
// server's root-gathering) into a double-digit-second freeze of every
// concurrent HTTP request.

/**
 * Sweep one repo's ended, merged session worktrees. Never throws (every git
 * call is individually try/caught) - the caller can run this on the
 * inventory-scan cadence without risking the scan loop.
 * @param repo           absolute path to the repo whose worktrees to sweep
 * @param worktreesDir   if given, only `session/*` worktrees rooted under this
 *                       dir are ever considered (defense in depth: a
 *                       coincidentally-named branch checked out elsewhere by
 *                       hand is never touched); non-session entries pass
 *                       through regardless since they are never swept anyway
 * @param liveSessionIds session ids currently live - never swept
 * @param liveDirs       cwds of non-ended sessions (see planSweep)
 * @param liveJobIds     runner ledger keys with a job in flight (see planSweep).
 *                       Gates BOTH passes below: the worktree sweep and the
 *                       orphan-branch pass. The orphan pass needs it too,
 *                       because a live job's worktree can legitimately be
 *                       missing from `git worktree list` (a partially-failed
 *                       remove leaves exactly that state), which would
 *                       otherwise make its branch look like reapable debris.
 * @param exec           (file, args) -> stdout | Promise<stdout>, injected (real git in prod, fake in tests)
 * @param onRemove       optional ({ dir, branch, kind }) => void, called once per
 *                       actual removal (kind: 'worktree' | 'orphan-branch'), so
 *                       the caller can make it durable (glmps-53: "log
 *                       every sweeper removal with the reason"). A throwing
 *                       callback is swallowed - instrumentation must never break
 *                       the sweep.
 * @param guard          optional ({ dir, branch }) => { remove, reason } | Promise of it,
 *                       asked just before each removal. The server uses it to record a
 *                       card's worktree outcome and refuse anything that would lose
 *                       work. A refusal, or a throw, keeps the worktree.
 * @returns { removed: [{ dir, branch }], kept: [entry, ...] }
 */
export async function sweepSessionWorktrees({ repo, worktreesDir = null, liveSessionIds = [], liveDirs = [], liveJobIds = [], exec, onRemove = null, guard = null, cherryCache = null } = {}) {
  const liveJobs = new Set(liveJobIds);
  const report = (row) => { try { onRemove?.(row); } catch { /* never break the sweep */ } };
  const listing = parseWorktreeList(await exec(...toPair(listWorktreesRecipe({ repo }))));
  // Candidates are the worktrees this orchestrator created: anything on a
  // session/* branch, plus (glmps-117) anything living under the managed
  // worktrees dir whatever its branch is called, which is what covers
  // harness-native Agent(isolation:'worktree') dirs and lane-*/agent-* dirs.
  // The repo's own main worktree qualifies as neither, so it is never a
  // candidate. `removed`/`kept` only ever describe worktrees actually considered.
  const sessionEntries = listing.filter((w) => {
    const branch = w?.branch ?? '';
    if (SESSION_BRANCH_RE.test(branch)) return !worktreesDir || underDir(w.dir, worktreesDir);
    return !!worktreesDir && underDir(w.dir, worktreesDir);
  });

  // Read once up front: the tips key the cherry cache, and the orphan pass
  // below reuses the list. A failed read leaves both uncached and skips orphans.
  let refs = null;
  try { refs = parseRefList(await exec(...toPair(forEachRefRecipe({ repo })))); } catch { /* best-effort */ }
  const tips = new Map((refs ?? []).filter((r) => r.sha).map((r) => [r.name, r.sha]));
  const { base, baseSha } = await resolveDefaultBase({ repo, exec, refs });
  const cherry = (branch, branchSha) => cherryFor({ exec, cache: cherryCache, repo, base, baseSha, branch, branchSha });
  const cherryByBranch = {};
  await Promise.all(sessionEntries.map(async (w) => {
    try {
      cherryByBranch[w.branch] = await cherry(w.branch, w.head ?? tips.get(w.branch));
    } catch {
      // Can't confirm merge status -> fail open as "unmerged" so it's kept, not swept.
      cherryByBranch[w.branch] = { unmerged: 1, equivalent: 0 };
    }
  }));

  const { remove, keep } = planSweep({ worktrees: sessionEntries, liveSessionIds, liveDirs, liveJobIds, cherryByBranch, managedDir: worktreesDir });

  const removed = [];
  const kept = [...keep];
  for (const item of remove) {
    if (guard) {
      let verdict = null;
      try { verdict = await guard({ dir: item.dir, branch: item.branch }); } catch { /* no evidence: keep */ }
      if (!verdict?.remove) { kept.push(item); continue; }
    }
    try {
      await exec(...toPair(worktreeRemoveSafeRecipe({ repo, dir: item.dir })));
    } catch {
      kept.push(item); // e.g. dirty tree - git refuses without --force; never force it
      continue;
    }
    try { await exec(...toPair(deleteBranchRecipe({ repo, branch: item.branch }))); } catch { /* best-effort */ }
    removed.push(item);
    report({ ...item, kind: 'worktree' });
  }
  try { await exec(...toPair(worktreePruneRecipe({ repo }))); } catch { /* best-effort */ }

  // Orphaned session branches: a branch delete can fail transiently (e.g. an
  // index.lock from a concurrent hook rebuild) and the next sweep would never
  // retry it - the branch no longer appears in `worktree list`. So also delete
  // fully-merged session/* branches that have no worktree; `-d` still refuses
  // anything unmerged, so this can never destroy work.
  try {
    // Every worktree, not just the sweep candidates: a card/* branch checked out
    // in a hand-made worktree outside the managed dir is not an orphan.
    const withWorktree = new Set(listing.map(w => w.branch));
    if (!refs) throw new Error('refs unreadable');
    const orphanResults = await Promise.all(refs
      .filter(ref => sweepableOrphanBranch(ref.name) && !withWorktree.has(ref.name)
        && !heldByLiveJob(ref.name, liveJobs))
      .map(async (ref) => {
        let unmerged = 1;
        try { unmerged = (await cherry(ref.name, ref.sha)).unmerged; } catch {}
        if (unmerged !== 0) return null;
        try {
          await exec(...toPair(deleteBranchRecipe({ repo, branch: ref.name })));
          report({ dir: null, branch: ref.name, kind: 'orphan-branch' });
          return { dir: null, branch: ref.name };
        } catch { return null; /* best-effort, retried next sweep */ }
      }));
    removed.push(...orphanResults.filter(Boolean));
  } catch { /* best-effort */ }
  return { removed, kept };
}
