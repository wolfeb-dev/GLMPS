import { test } from 'node:test';
import assert from 'node:assert/strict';
import {
  inboundLinks, salience, projectAffinity, selectWorkingSet, excerptFor,
} from '../lib/evaluation/memory-working-set.js';

test('counts [[wikilinks]] pointing at each target', () => {
  const bodies = {
    'a.md': 'see [[b]] and also [[c]]',
    'b.md': 'refers to [[c]]',
    'c.md': 'no links here',
  };
  const inb = inboundLinks(bodies);
  assert.equal(inb.get('c.md'), 2);
  assert.equal(inb.get('b.md'), 1);
  assert.equal(inb.get('a.md') ?? 0, 0);
});

test('a self-link does not count as inbound', () => {
  assert.equal(inboundLinks({ 'a.md': 'I link to [[a]] myself' }).get('a.md') ?? 0, 0);
});

test('links to nonexistent facts are ignored rather than counted', () => {
  const inb = inboundLinks({ 'a.md': 'points at [[does-not-exist]]' });
  assert.equal(inb.get('does-not-exist.md') ?? 0, 0);
});

// Named salience, NOT importance: it measures connectedness and
// constraint-ness, which is a proxy, not the thing itself.
test('a pinned fact scores above an unpinned one', () => {
  assert.ok(salience({ pinned: true, inbound: 0 }) > salience({ pinned: false, inbound: 0 }));
});

test('more inbound links scores higher', () => {
  assert.ok(salience({ pinned: false, inbound: 5 }) > salience({ pinned: false, inbound: 1 }));
});

test('inbound links saturate so one hub fact cannot dominate the whole ranking', () => {
  const a = salience({ pinned: false, inbound: 8 });
  const b = salience({ pinned: false, inbound: 40 });
  assert.ok(b > a, 'still monotonic');
  assert.ok(b - a < salience({ pinned: false, inbound: 2 }), 'but strongly diminishing');
});

// The single biggest cheap win: a Harbor session should not carry GLMPS facts.
test('matches a fact naming the current project directory', () => {
  assert.ok(projectAffinity('canonical bars live in D:\\Harbor-App/data', 'D:\\Harbor-App') > 0);
});

test('matches on the project basename alone', () => {
  assert.ok(projectAffinity('the Harbor-App resampling gotcha', 'D:\\Harbor-App') > 0);
});

test('does not match an unrelated project', () => {
  assert.equal(projectAffinity('the GLMPS wiki pipeline uses graphify', 'D:\\Harbor-App'), 0);
});

test('is case-insensitive and separator-insensitive', () => {
  assert.ok(projectAffinity('see d:/harbor-app/data', 'D:\\Harbor-App') > 0);
});

test('an empty cwd yields no affinity rather than matching everything', () => {
  assert.equal(projectAffinity('anything at all', ''), 0);
});

const bodies = {
  'harbor-bars.md': 'Harbor-App bars are close-stamped; resample with label=right',
  'glmps-wiki.md': 'the GLMPS wiki is generated by graphify and agy',
  'git-symlink.md': 'ln -s copies instead of symlinking under MSYS',
};

test('project-relevant facts outrank unrelated ones', () => {
  const ws = selectWorkingSet({ bodies, cwd: 'D:\\Harbor-App', usage: {}, pinned: new Set(), k: 3 });
  assert.equal(ws[0].target, 'harbor-bars.md');
});

test('k bounds the working set', () => {
  const ws = selectWorkingSet({ bodies, cwd: 'D:\\Harbor-App', usage: {}, pinned: new Set(), k: 1 });
  assert.equal(ws.length, 1);
});

test('read frequency contributes but does not overwhelm project affinity', () => {
  const usage = { 'glmps-wiki.md': { reads: 50, exposureSessions: 50 } };
  const ws = selectWorkingSet({ bodies, cwd: 'D:\\Harbor-App', usage, pinned: new Set(), k: 3 });
  assert.equal(ws[0].target, 'harbor-bars.md', 'a hot but irrelevant fact must not win');
});

test('with no cwd signal it degrades to salience plus usage rather than erroring', () => {
  const usage = { 'git-symlink.md': { reads: 20, exposureSessions: 20 } };
  const ws = selectWorkingSet({ bodies, cwd: '', usage, pinned: new Set(), k: 1 });
  assert.equal(ws[0].target, 'git-symlink.md');
});

test('every result carries its score components so the ranking is auditable', () => {
  const [top] = selectWorkingSet({ bodies, cwd: 'D:\\Harbor-App', usage: {}, pinned: new Set(), k: 1 });
  assert.equal(typeof top.score, 'number');
  assert.equal(typeof top.affinity, 'number');
  assert.equal(typeof top.salience, 'number');
});

test('an empty corpus yields an empty working set', () => {
  assert.deepEqual(selectWorkingSet({ bodies: {}, cwd: 'D:\\x', usage: {}, pinned: new Set(), k: 5 }), []);
});

// Promoting a globally-hot but project-irrelevant fact just restates the index
// at ~6x the tokens. In a repo no memory mentions, the correct cost is zero.
test('requireAffinity drops facts with no project relevance', () => {
  const ws = selectWorkingSet({
    bodies, cwd: 'D:\\Harbor-App', usage: {}, pinned: new Set(), k: 10, requireAffinity: true,
  });
  assert.deepEqual(ws.map((w) => w.target), ['harbor-bars.md']);
});

test('requireAffinity yields an empty set for an unrelated project', () => {
  const ws = selectWorkingSet({
    bodies, cwd: 'D:\\totally-unrelated-repo', usage: {}, pinned: new Set(), k: 10, requireAffinity: true,
  });
  assert.deepEqual(ws, [], 'no promotion, no token cost');
});

// L1 is ~32 tokens (the index hook). L3 is the whole 6KB body. L2 is the
// missing middle: enough to answer without paying for the full body.
test('excerpt strips frontmatter and is bounded', () => {
  const body = '---\nname: x\ndescription: d\n---\n\n' + 'word '.repeat(500);
  const ex = excerptFor(body, 800);
  assert.ok(!ex.includes('description:'), 'frontmatter is metadata, not content');
  assert.ok(ex.length <= 800);
});

test('excerpt does not split a word', () => {
  const ex = excerptFor('---\nname: x\n---\n\nalpha bravo charlie delta echo', 20);
  assert.ok(!/\w$/.test(ex.replace(/\.\.\.$/, '')) || 'alpha bravo charlie delta echo'.split(' ').includes(
    ex.replace(/\.\.\.$/, '').trim().split(' ').pop(),
  ));
});

test('a short body is returned whole with no truncation marker', () => {
  assert.equal(excerptFor('---\nname: x\n---\n\nshort body', 800), 'short body');
});
